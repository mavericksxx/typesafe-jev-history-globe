// One-off generator: derives a [country name -> [lon, lat]] centroid table
// from the world-atlas topojson land data already bundled with the repo
// (the same dataset src/globe/land.ts renders), rather than hand-typing
// coordinates. Writes src/live/countryCentroids.ts.
// Usage: node scripts/gen-country-centroids.mjs
import { feature } from "topojson-client";
import { geoCentroid, geoArea } from "d3-geo";
import { writeFileSync } from "node:fs";
import topo from "../node_modules/world-atlas/countries-110m.json" with { type: "json" };

/** Centroid of a country's LARGEST landmass, not of all its polygons.
 * Averaging every polygon puts a country with distant overseas territories in
 * open water — France came out at [-6.8, 43.14], in the Bay of Biscay, because
 * French Guiana and the Caribbean départements drag the mean west. Pinning
 * "the storming of the Bastille" into the sea is worse than ignoring the
 * outlying territories, so we take the mainland the event most likely refers
 * to. Single-polygon countries are unaffected. */
function mainlandCentroid(f) {
  const g = f.geometry;
  if (!g) return null;
  if (g.type !== "MultiPolygon") return geoCentroid(f);
  let best = null;
  let bestArea = -1;
  for (const coords of g.coordinates) {
    const part = { type: "Polygon", coordinates: coords };
    const area = geoArea(part);
    if (area > bestArea) {
      bestArea = area;
      best = part;
    }
  }
  return best ? geoCentroid(best) : geoCentroid(f);
}

const fc = feature(topo, topo.objects.countries);
const entries = [];
for (const f of fc.features) {
  const name = f.properties?.name;
  if (!name || name === "Antarctica") continue;
  const c = mainlandCentroid(f);
  if (!c || Number.isNaN(c[0]) || Number.isNaN(c[1])) continue;
  entries.push([name, [Number(c[0].toFixed(2)), Number(c[1].toFixed(2))]]);
}
entries.sort((a, b) => a[0].localeCompare(b[0]));

const jsonObj = Object.fromEntries(entries);
writeFileSync(
  new URL("../src/live/countryCentroids.json", import.meta.url),
  JSON.stringify(jsonObj, null, 2) + "\n"
);

const out = `// GENERATED by scripts/gen-country-centroids.mjs — do not hand-edit.
// Centroids are the geoCentroid() of each country's LARGEST landmass in the same
// world-atlas 110m land data src/globe/land.ts already renders (a
// land-area centroid, not a capital or population centroid — consistent
// with how the rest of the app already draws these borders). Kept as plain
// JSON (countryCentroids.json) so both this typed module AND the Worker
// (worker/src/index.ts) and probe scripts (plain .mjs, no ts-node) can all
// read the exact same generated table without re-deriving it.
import raw from "./countryCentroids.json";

export const COUNTRY_CENTROIDS: Record<string, [lon: number, lat: number]> = raw as unknown as Record<
  string,
  [number, number]
>;
`;
writeFileSync(new URL("../src/live/countryCentroids.ts", import.meta.url), out);
console.log(`wrote ${entries.length} country centroids`);
